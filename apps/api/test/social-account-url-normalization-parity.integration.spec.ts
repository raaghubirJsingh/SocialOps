/**
 * Parity test for Decision 021 (global social-account profile URL uniqueness):
 * it runs the migration's ACTUAL SQL backfill pipeline (20261004211630) against a
 * throwaway row set and requires the resulting `normalizedUrl` to match the
 * TypeScript normalizer for every reference fixture in
 * `profile-url-normalization.fixtures.ts`.
 *
 * ISOLATION: requires DATABASE_URL to point at the isolated test database
 * (name must end in `_test` / `_itest`), matching the guard already used by the
 * rest of the suite. It never touches the development database.
 *
 * Precondition: the server-side migration that adds `normalizedUrl` must be
 * applied to the isolated database (prisma migrate deploy or the CI step)
 * before this test runs.
 */
import { readFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
import { PROFILE_URL_CASES } from '../src/social-accounts/lib/profile-url-normalization.fixtures.js';
import { normalizeProfileUrl } from '../src/social-accounts/lib/profile-url-normalization.js';

const prisma = new PrismaClient();

// The guard runs at module load, before any Prisma call can be made.
const dbName = new URL(process.env.DATABASE_URL ?? '').pathname.slice(1);
if (!/(^|_)(test|itest)$/.test(dbName)) {
  throw new Error(
    `REFUSING TO RUN: DATABASE_URL points at "${dbName}", which is not an ` +
      'isolated test database. Integration specs must never target the ' +
      'development database.',
  );
}

// Index name generated by Prisma for `normalizedUrl String? @unique` in the
// SocialAccount model (matches the migration's CREATE UNIQUE INDEX).
const NORMALIZED_URL_INDEX = 'SocialAccount_normalizedUrl_key';

describe('Decision 021: profile URL normalization parity (TypeScript vs SQL backfill)', () => {
  // The fixtures deliberately include equivalence classes — multiple profileUrl
  // inputs that collapse to the SAME canonical normalizedUrl (e.g.
  // "instagram.com/x", "https://instagram.com/x", and
  // "HTTPS://WWW.Instagram.COM/X" all -> "instagram.com/x"). The migration's
  // unique index on normalizedUrl would REJECT those duplicate assignments
  // during the backfill UPDATE, so it must be dropped before the backfill runs
  // and restored afterwards. This test verifies backfill KEY COMPUTATION
  // parity, not uniqueness enforcement (which the migration already guards at
  // step 3 with its duplicate-check DO block).
  beforeAll(async () => {
    // Defensive cleanup: remove any leftover rows from a previous crashed/failed run
    // so the unique-index restore in afterAll can succeed.
    await prisma.socialAccount.deleteMany({
      where: { handle: 'parity-test' },
    });
    await prisma.$executeRawUnsafe(
      `DROP INDEX IF EXISTS "${NORMALIZED_URL_INDEX}";`,
    );
  });

  afterAll(async () => {
    // Remove the throwaway rows before restoring the unique index so that
    // equivalence-class duplicates (intentional in the fixtures) don't
    // trip the CREATE UNIQUE INDEX. Also drop+recreate to guarantee a
    // clean state if a previous run left a stale unique index.
    await prisma.socialAccount.deleteMany({
      where: { handle: 'parity-test' },
    });
    await prisma.$executeRawUnsafe(
      `DROP INDEX IF EXISTS "${NORMALIZED_URL_INDEX}";`,
    );
    await prisma.$executeRawUnsafe(
      `CREATE UNIQUE INDEX "${NORMALIZED_URL_INDEX}" ` +
        'ON "SocialAccount"("normalizedUrl");',
    );
    await prisma.$disconnect();
  });

  it('backfill keys match the TypeScript normalizer for every reference fixture', async () => {
    // Rows with a known profileUrl and no key yet.
    const rows = await Promise.all(
      PROFILE_URL_CASES.map(async ([input]) => {
        // Use the Prisma-returned id, NOT a client-generated one — the DB
        // assigns its own UUID and we need that to match returned rows.
        const created = await prisma.socialAccount.create({
          data: {
            client: {
              connect: {
                id: (await prisma.client.findFirst({ select: { id: true } }))!.id,
              },
            },
            platform: 'INSTAGRAM',
            profileUrl: input,
            handle: 'parity-test',
          },
          select: { id: true },
        });
        return { id: created.id, input };
      }),
    );
    const rowById = new Map<string, string>(rows.map((r) => [r.id, r.input]));

    try {
      // Extract the migration's exact backfill statement (20261004211630).
      const migrationSql = readFileSync(
        new URL(
          '../prisma/migrations/20261004211630_social_account_global_url_uniqueness/migration.sql',
          import.meta.url,
        ),
        'utf8',
      );
      const backfill = migrationSql.match(
        /UPDATE "SocialAccount" AS sa[\s\S]*?WHERE sa\."id" = k\."id";/,
      );
      if (!backfill) {
        throw new Error(
          'Decision 021 backfill statement not found in the migration file',
        );
      }

      // Use $queryRawUnsafe (NOT $queryRaw): the backfill SQL is extracted
      // verbatim from the migration file and must be injected as raw SQL.
      // $queryRaw treats template interpolations as parameterized values and
      // would escape the entire SQL string as a single string literal,
      // producing broken SQL. $queryRawUnsafe passes the string through
      // without parameterization — safe here because the source is a vetted
      // committed migration file, not user input.
      // Strip the trailing semicolon from the backfill so RETURNING is part of
      // the same UPDATE statement (a semicolon would terminate it and leave
      // RETURNING as a dangling, invalid second statement).
      const results = await prisma.$queryRawUnsafe<{
        id: string;
        key: string | null;
      }[]>(`${backfill[0].replace(/;\s*$/, '')} RETURNING sa."id" AS id, sa."normalizedUrl" AS key`);

      expect(results).toHaveLength(PROFILE_URL_CASES.length);
      for (const r of results) {
        const input = rowById.get(r.id);
        if (!input) throw new Error(`unexpected backfill row id "${r.id}"`);
        // The TypeScript normalizer is the reference for this decision; the SQL
        // backfill must compute the same key for the same input.
        expect(r.key).toBe(normalizeProfileUrl(input));
      }
    } finally {
      // Test rows are isolated and cleaned up.
      await prisma.socialAccount.deleteMany({
        where: { id: { in: rows.map((r) => r.id) } },
      });
    }
  });
});